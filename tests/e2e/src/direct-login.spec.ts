import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { ReferralReceiptSchema, RecheckResultSchema, SearchRecoverySchema } from '@torob-ticket/contracts';

test('Direct Login connects a provider, verifies consent and resumes the exact offer with one acquisition', async ({ page, context }, info) => {
  const root = process.env.DIRECT_LOGIN_EVIDENCE_DIR ?? info.outputPath('captures'); mkdirSync(root, { recursive: true });
  await context.request.post('/api/v1/demo/session', { data: { seed: 8887, anchorInstant: '2026-10-25T06:00:00Z' } });
  await page.goto('/admin/direct-login');
  await expect(page.getByRole('heading', { name: 'Direct Login', exact: true })).toBeVisible();
  const providerRow=page.getByRole('table').first().getByRole('row').filter({hasText:'راه‌آرا'});
  await providerRow.getByRole('button', {name:/^(Connect provider|Edit connection)$/}).click();
  await page.getByLabel('Integration',{exact:true}).selectOption('reference');
  await page.getByLabel('Callback URL',{exact:true}).fill(`${process.env.E2E_BASE_URL}/api/v1/reference-provider/demo-provider-01/callback`);
  await page.getByLabel('Login initiation URL',{exact:true}).fill(`${process.env.E2E_BASE_URL}/api/v1/reference-provider/demo-provider-01/start`);
  await page.getByLabel('Acquisition rate · IRR').fill('70000');
  await page.getByRole('button', { name: 'Save connection' }).click();
  await expect(page.getByText('Client secret · copy now')).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  const started = SearchRecoverySchema.parse(await (await context.request.post('/api/v1/searches', { data: { query: { mode: 'flight', scope: 'domestic', tripType: 'one-way', originCityId: 'tehran', destinationCityId: 'mashhad', departureDate: '2026-10-25', party: { adults: 1, children: 0, infants: 0 }, classCode: 'economy', filters: {}, sort: 'cheapest' }, clientGeneration: randomUUID() } })).json());
  let snapshot = started.snapshot;
  await expect.poll(async () => { snapshot = SearchRecoverySchema.parse(await (await context.request.get(`/api/v1/searches/${snapshot.searchId}`)).json()).snapshot; return snapshot.status; }, { timeout: 15000 }).toBe('complete');
  const quote = snapshot.groups.flatMap(g => g.eligibleQuotes).find(q => q.providerId === 'demo-provider-01')!;
  const checked = RecheckResultSchema.parse(await (await context.request.post('/api/v1/referrals/prepare', { data: { kind: 'transport', quoteId: quote.quoteId, quoteVersion: quote.version } })).json());
  if (checked.status === 'unavailable') throw Error('Expected available referral');
  const receipt = ReferralReceiptSchema.parse(await (await context.request.post('/api/v1/referrals/confirm', { data: { intentId: checked.intent.intentId, acceptedQuoteVersion: checked.intent.selection.quoteVersion, idempotencyKey: randomUUID() } })).json());
  await page.goto(`/api/v1/referrals/${receipt.referralId}/outbound`);
  await expect(page.getByRole('link', { name: 'رفتن به سایت فروشنده', exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(root, 'choice-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: 'ادامه با ترب‌تیکت', exact: true }).click();
  await page.getByLabel('شماره همراه', { exact: true }).fill('+989121234567');
  await page.getByRole('button', { name: 'دریافت کد تأیید', exact: true }).click();
  const admin = await context.newPage(); await admin.goto('/admin/direct-login');
  await admin.getByRole('button', { name: 'Refresh messages' }).click();
  const row = admin.getByRole('row').filter({ hasText: '+989121234567' }); await expect(row).toBeVisible();
  const code = await row.locator('code').innerText();
  await page.getByLabel('کد تأیید', { exact: true }).fill(code);
  await page.getByRole('button', { name: 'تأیید و ورود', exact: true }).click();
  await expect(page.getByRole('button', { name: 'اجازه و ادامه', exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(root, 'consent-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'اجازه و ادامه', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/reference-provider/demo-provider-01\\?referral=${receipt.referralId}$`));
  await expect(page.getByText('به حساب خود خوش آمدید')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'پیشنهاد انتخاب‌شده شما' })).toBeVisible();
  await page.screenshot({ path: resolve(root, 'provider-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: resolve(root, 'provider-mobile.png'), fullPage: true });
  await admin.getByRole('button', { name: 'Refresh messages' }).click();
  await expect(admin.getByRole('cell', { name: 'local-enrollment', exact: false })).toBeVisible();
  await admin.screenshot({ path: resolve(root, 'admin-evidence.png'), fullPage: true });
  const evidence = await (await context.request.get('/api/v1/admin/direct-login')).json();
  expect(evidence.totals.newAccounts).toBe(1); expect(evidence.totals.amountRial).toBe('70000'); expect(evidence.acquisitions[0].referralId).toBe(receipt.referralId);
  expect((await (await context.request.get('/api/v1/admin/traffic')).json()).totals.outbound).toBe(1);
  await admin.close();
});
